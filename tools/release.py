"""Build and validate the third-party materials for the Windows release.

The checked-in lock is reviewed input, never regenerated by a normal build.
Only build-time checks enforce its hashes; users may replace LGPL libraries.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata as metadata
import json
import re
import shutil
import struct
import sys
import tarfile
import urllib.request
import zipfile
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path

from cast_to_tv import __version__

EXTERNAL = ("pystray", "zeroconf")
LOCK = "release-lock.json"


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def runtime_versions() -> dict:
    import ssl
    import zlib
    import numpy
    from PIL import features
    base = Path(sys.base_prefix)
    versions = {"Python": sys.version.split()[0], "OpenSSL": ssl.OPENSSL_VERSION,
                "zlib": zlib.ZLIB_RUNTIME_VERSION,
                "Pillow": {name: features.version(name) for name in features.get_supported()},
                "OpenBLAS": numpy.show_config(mode="dicts")["Build Dependencies"]["blas"]["version"]}
    for name, script in (("Tcl", "tcl8.6/init.tcl"), ("Tk", "tk8.6/tk.tcl")):
        contents = (base / "tcl" / script).read_text(encoding="utf-8")
        versions[name] = re.search(r"package require -exact " + name + r"\s+(\S+)", contents)[1]
    distribution = metadata.distribution("pillow")
    license_file = next(f for f in distribution.files if str(f).endswith("dist-info/licenses/LICENSE"))
    versions["Pillow bundled libraries"] = re.findall(r"^===== (.+) =====$",
        Path(distribution.locate_file(license_file)).read_text(encoding="utf-8"), flags=re.MULTILINE)
    return versions


def load_lock(root: Path) -> dict:
    lock = json.loads((root / "tools" / LOCK).read_text(encoding="utf-8"))
    if lock["python"] != sys.version.split()[0] or lock["abi"] != sys.implementation.cache_tag:
        raise RuntimeError("Python version/ABI differs from tools/release-lock.json")
    if lock["architecture"] != "win_amd64" or struct.calcsize("P") != 8 or sys.platform != "win32":
        raise RuntimeError("Release requires 64-bit Windows Python")
    for name, expected in lock.get("build_tools", {}).items():
        if metadata.version(name) != expected:
            raise RuntimeError(f"Build tool version drift: {name}; expected {expected}")
    native = root / ".tmp/native-build/openscreen"
    for relative, expected in lock.get("native_notice_inputs", {}).items():
        path = native / relative
        if not path.is_file() or digest(path) != expected:
            raise RuntimeError(f"Missing or changed native notice input: {relative}")
    for name, package in lock["packages"].items():
        distribution = metadata.distribution(name)
        if distribution.version != package["version"]:
            raise RuntimeError(f"Version drift: {name}: expected {package['version']}, found {distribution.version}")
        if not package["notices"]:
            raise RuntimeError(f"Missing notices: {name}")
        for notice in package["notices"]:
            path = Path(distribution.locate_file(notice["path"]))
            if not path.is_file() or digest(path) != notice["sha256"]:
                raise RuntimeError(f"Missing or changed notice: {name}/{notice['path']}")
    return lock


def artifact(root: Path, pin: dict) -> Path:
    filename = pin["filename"]
    if Path(filename).name != filename:
        raise RuntimeError("Artifact filename must be a basename")
    cache = root / ".tmp" / "packaging" / "downloads"
    cache.mkdir(parents=True, exist_ok=True)
    path = cache / filename
    if not path.exists():
        print(f"Fetching locked release artifact: {filename}", flush=True)
        # Some public license hosts reject urllib's default user agent.
        request = urllib.request.Request(pin["url"], headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request, timeout=45) as response:
            data = response.read()
        if hashlib.sha256(data).hexdigest() != pin["sha256"]:
            raise RuntimeError(f"Upstream artifact checksum mismatch: {filename}")
        path.write_bytes(data)
    if digest(path) != pin["sha256"]:
        raise RuntimeError(f"Cached artifact checksum mismatch: {filename}")
    return path


class LicenseText(HTMLParser):
    """Retain license wording from official HTML documents, without scripts."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self.skipping = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self.skipping += 1
        if tag in ("p", "div", "br", "li", "pre", "h1", "h2", "h3"):
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in ("style", "script"):
            self.skipping -= 1
        if tag in ("p", "div", "li", "pre"):
            self.parts.append("\n")

    def handle_data(self, data):
        if not self.skipping:
            self.parts.append(data)


def source_files(path: Path) -> dict[str, bytes]:
    # Read archives without extracting paths or executing upstream build code.
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as archive:
            return {n: archive.read(n) for n in archive.namelist() if not n.endswith("/")}
    with tarfile.open(path) as archive:
        return {m.name: archive.extractfile(m).read() for m in archive.getmembers() if m.isfile()}


def verify_source(name: str, distribution, archive: Path, prefix: str) -> None:
    files = source_files(archive)
    count = 0
    # Include source-form data such as certifi's CA bundle, not just Python code.
    for entry in distribution.files or []:
        relative = str(entry).replace("\\", "/")
        if relative.startswith(name + "/") and (relative.endswith(".py") or relative.endswith(".pem")):
            candidate = prefix + relative
            installed = Path(distribution.locate_file(entry)).read_bytes()
            if candidate not in files or files[candidate].replace(b"\r\n", b"\n") != installed.replace(b"\r\n", b"\n"):
                raise RuntimeError(f"Source does not correspond to installed file: {relative}")
            count += 1
    if not count:
        raise RuntimeError(f"No corresponding source checked for {name}")


def safe_reset(path: Path, parent: Path) -> None:
    if path.resolve().parent != parent.resolve() or path.name != "third-party":
        raise RuntimeError(f"Refusing to reset unexpected directory: {path}")
    if path.exists():
        if path.is_symlink() or path.is_junction():
            raise RuntimeError(f"Refusing to reset linked directory: {path}")
        shutil.rmtree(path)
    path.mkdir(parents=True)


def prepare_release(root: Path) -> Path:
    lock = load_lock(root)
    if runtime_versions() != lock["runtime_components"]:
        raise RuntimeError("Bundled runtime component versions differ from the reviewed release lock")
    release = root / ".tmp" / "packaging" / "third-party"
    safe_reset(release, release.parent)
    for folder in ("licenses", "sources", "runtime"):
        (release / folder).mkdir()
    shutil.copyfile(root / "docs" / "third-party-distribution.txt", release / "README.txt")
    # PyInstaller Analysis records this path; the completed inventory is written
    # after analysis and before assembling the executable.
    (release / "NOTICES.txt").write_text("Release inventory pending analysis.\n", encoding="utf-8")
    for name in EXTERNAL:
        distribution = metadata.distribution(name)
        package = Path(distribution.locate_file(name))
        shutil.copytree(package, release / "runtime" / name,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        info = next(f for f in distribution.files if str(f).endswith(".dist-info/METADATA"))
        shutil.copytree(Path(distribution.locate_file(info)).parent,
                        release / "runtime" / Path(str(info)).parent.name)
    for name, package in lock["packages"].items():
        if package.get("source"):
            pin = lock["artifacts"][package["source"]]
            path = artifact(root, pin)
            verify_source(name, metadata.distribution(name), path, package["source_prefix"])
            shutil.copyfile(path, release / "sources" / path.name)
    for key in lock["runtime_notices"]:
        pin = lock["artifacts"][key]
        path = artifact(root, pin)
        if pin.get("docx"):
            with zipfile.ZipFile(path) as document:
                tree = ET.fromstring(document.read("word/document.xml"))
            text = "\n".join("".join(node.itertext()) for node in tree.iter("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}p"))
        else:
            text = path.read_text(encoding="utf-8-sig")
        if pin.get("html"):
            parser = LicenseText()
            parser.feed(text)
            text = "".join(parser.parts)
        (release / "licenses" / (key + ".txt")).write_text(text, encoding="utf-8")
    archive_cache = {}
    for index, notice in enumerate(lock["archive_notices"]):
        key = notice["artifact"]
        if key not in archive_cache:
            archive_cache[key] = source_files(artifact(root, lock["artifacts"][key]))
        text = archive_cache[key][notice["path"]].decode("utf-8")
        if notice.get("header"):
            end = text.find("*/")
            if end < 0 or "Permission is hereby granted" not in text[:end]:
                raise RuntimeError(f"Missing embedded license header: {notice['path']}")
            text = text[:end + 2]
        (release / "licenses" / f"archive-{index:02d}.txt").write_text(
            f"Source: {lock['artifacts'][key]['url']}\nFile: {notice['path']}\n\n{text}", encoding="utf-8")
    shutil.copyfile(Path(sys.base_prefix) / "LICENSE.txt", release / "licenses" / "python-installed.txt")
    return release


def external_entry(entry) -> bool:
    target = entry[0].replace("\\", "/").lower()
    return any(target == name or target.startswith(name + ".") or target.startswith(name + "/")
               or target.startswith(name + "-") for name in EXTERNAL)


def system_entry(entry) -> bool:
    # These are Windows 10+ OS components. Do not accidentally redistribute
    # downlevel copies picked up from unrelated programs on the build PATH.
    name = Path(entry[0]).name.lower()
    return name.startswith("api-ms-win-") or name == "ucrtbase.dll"


def finish_release(root: Path, release: Path, analysis) -> None:
    lock = load_lock(root)
    analysis.binaries = [entry for entry in analysis.binaries if not system_entry(entry)]
    records = list(analysis.pure) + list(analysis.binaries) + list(analysis.datas) + list(analysis.scripts)
    ownership = {}
    for distribution in metadata.distributions():
        name = canonical(distribution.metadata["Name"])
        for entry in distribution.files or []:
            ownership[str(Path(distribution.locate_file(entry)).resolve()).casefold()] = name
    used = set(EXTERNAL)
    inventory = []
    base = Path(sys.base_prefix).resolve()
    helper = root / ".tmp/native-build/cmake/Release/cast_streaming_probe.exe"
    for target, source, kind in records:
        if "autocommand" in target.lower():
            raise RuntimeError("Vendored LGPL autocommand requires a separate replacement review")
        path = Path(source).resolve()
        owner = ownership.get(str(path).casefold())
        if owner:
            if owner not in lock["packages"]:
                raise RuntimeError(f"Unreviewed bundled distribution: {owner}: {target}")
            used.add(owner)
        elif target.replace("\\", "/") == "base_library.zip":
            owner = "python-runtime"
        elif path == release / "NOTICES.txt":
            owner = "third-party-notices"
        elif path.is_relative_to(root.resolve()):
            owner = "cast-to-tv"
        elif path.is_relative_to(base):
            # Only reviewed Python installation roots; never blanket-accept
            # unknown packages under site-packages.
            relative = path.relative_to(base)
            if "site-packages" in relative.parts:
                raise RuntimeError(f"Unowned site-packages file: {path}")
            if relative.parts[0].lower() not in ("lib", "dlls", "tcl") and path.name.lower() not in (
                    "python313.dll", "python3.dll", "vcruntime140.dll", "vcruntime140_1.dll"):
                raise RuntimeError(f"Unreviewed Python runtime file: {path}")
            owner = "python-runtime"
        else:
            raise RuntimeError(f"Unaccounted bundled file: {target}: {source}")
        inventory.append({"file": target, "kind": kind, "component": owner,
                          "location": "external" if external_entry((target, source, kind)) else "executable"})
    sections = [(release / "README.txt").read_text(encoding="utf-8")]
    components = []
    for name in sorted(used):
        pin = lock["packages"][name]
        distribution = metadata.distribution(name)
        notices = []
        for index, notice in enumerate(pin["notices"]):
            original = Path(distribution.locate_file(notice["path"]))
            destination = release / "licenses" / name / f"{index:02d}-{original.name}"
            destination.parent.mkdir(exist_ok=True)
            shutil.copyfile(original, destination)
            notices.append(destination.relative_to(release).as_posix())
            sections.append(f"\n{'=' * 72}\n{name} {pin['version']}\n"
                            f"{pin['license']}\n{pin['upstream']}\n{notice['path']}\n\n" +
                            original.read_text(encoding="utf-8-sig", errors="strict"))
        component = {k: pin[k] for k in ("version", "license", "upstream")}
        component.update(name=name, notices=notices)
        if pin.get("source"):
            asset = lock["artifacts"][pin["source"]]
            component["source"] = {**asset, "path": "sources/" + asset["filename"]}
        components.append(component)
    for path in sorted((release / "licenses").glob("*.txt")):
        sections.append(f"\n{'=' * 72}\n{path.stem}\n\n" + path.read_text(encoding="utf-8"))
    native = json.loads((root / "native/dependencies.json").read_text())
    if native != lock["native"]:
        raise RuntimeError("Native revisions differ from the reviewed release lock")
    if not helper.is_file():
        raise RuntimeError("Native helper missing; the release must preserve both casting modes")
    if digest(helper) != lock["native_helper_sha256"]:
        raise RuntimeError("Native helper differs from the reviewed release lock")
    inventory.append({"file": "native/cast_streaming_probe.exe", "kind": "DATA",
                      "component": "native-helper", "location": "executable", "sha256": digest(helper)})
    native_notice = root / "native/licenses/THIRD-PARTY-NOTICES.txt"
    sections.append(native_notice.read_text(encoding="utf-8"))
    shutil.copyfile(native_notice, release / "licenses" / "native.txt")
    (release / "NOTICES.txt").write_text("\n".join(sections), encoding="utf-8")
    # Include the complete externally copied packages, not only modules that
    # Analysis happened to traverse on this platform.
    for path in sorted((release / "runtime").rglob("*")):
        if path.is_file():
            component = next(name for name in EXTERNAL if path.relative_to(release / "runtime").parts[0].startswith(name))
            inventory.append({"file": path.relative_to(release).as_posix(), "kind": "EXTERNAL",
                              "component": component, "location": "external", "sha256": digest(path)})
    manifest = {"schema": 1, "python": lock["python"], "abi": lock["abi"],
                "components": components, "native": native, "runtime_notices": {
                    key: lock["artifacts"][key] for key in lock["runtime_notices"]},
                "archive_notices": lock["archive_notices"],
                "runtime_components": lock["runtime_components"],
                "native_helper_sha256": digest(helper), "files": inventory,
                "build": json.loads((root / ".tmp/packaging/build_info.json").read_text()),
                "release_lock_sha256": digest(root / "tools" / LOCK)}
    # All shipped support files are checked when validating a release, not at
    # launch. This intentionally does not prevent a user's library changes.
    manifest["support_files"] = {path.relative_to(release).as_posix(): digest(path)
                                 for path in release.rglob("*") if path.is_file()}
    write_json(release / "manifest.json", manifest)
    validate_release(release)
    print(f"Release inventory: {len(components)} Python components, {len(inventory)} files", flush=True)


def validate_release(release: Path) -> dict:
    manifest = json.loads((release / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("executable_sha256"):
        executable = release.parent / "CastToTV.exe"
        if not executable.is_file() or digest(executable) != manifest["executable_sha256"]:
            raise RuntimeError("Executable does not match the companion folder")
    for relative, expected in manifest["support_files"].items():
        path = release / relative
        if not path.resolve().is_relative_to(release.resolve()) or not path.is_file() or digest(path) != expected:
            raise RuntimeError(f"Missing or changed release material: {relative}")
    actual = {path.relative_to(release).as_posix() for path in release.rglob("*")
              if path.is_file() and path != release / "manifest.json"}
    if actual != set(manifest["support_files"]):
        raise RuntimeError("Unaccounted files in the third-party distribution")
    for name in EXTERNAL:
        if not (release / "runtime" / name / "__init__.py").is_file():
            raise RuntimeError(f"Missing external library: {name}")
    for component in manifest["components"]:
        if not component["notices"]:
            raise RuntimeError(f"Missing component notices: {component['name']}")
        if component["name"] in (*EXTERNAL, "certifi", "setuptools") and "source" not in component:
            raise RuntimeError(f"Missing required source: {component['name']}")
        if "source" in component:
            source = release / component["source"]["path"]
            if not source.is_file() or digest(source) != component["source"]["sha256"]:
                raise RuntimeError(f"Missing or mismatched source: {component['name']}")
    return manifest


def publish(root: Path) -> None:
    staged = root / ".tmp/packaging/third-party"
    validate_release(staged)
    output = root / "dist/third-party"
    if output.exists() and not (output / "manifest.json").is_file():
        raise RuntimeError("Refusing to replace an unrecognized dist/third-party folder")
    safe_reset(output, root / "dist")
    shutil.copytree(staged, output, dirs_exist_ok=True)
    manifest = json.loads((output / "manifest.json").read_text(encoding="utf-8"))
    manifest["executable_sha256"] = digest(root / "dist/CastToTV.exe")
    manifest["application_version"] = __version__
    write_json(output / "manifest.json", manifest)
    validate_release(output)


def archive_release(root: Path) -> Path:
    """Package only validated distribution files, excluding local application data."""
    distribution = root / "dist"
    release = distribution / "third-party"
    manifest = validate_release(release)
    if not manifest.get("executable_sha256") or manifest.get("application_version") != __version__:
        raise RuntimeError("Rebuild with build.ps1 before creating a release archive")
    archive = distribution / f"CastToTV-{__version__}-windows-x64.zip"
    temporary = archive.with_suffix(".zip.tmp")
    files = ["CastToTV.exe", "third-party/manifest.json"]
    files.extend(f"third-party/{relative}" for relative in sorted(manifest["support_files"]))
    try:
        with zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_DEFLATED) as output:
            for relative in files:
                output.write(distribution / relative, relative)
            license_path = root / "LICENSE"
            if license_path.is_file():
                output.write(license_path, "LICENSE")
        temporary.replace(archive)
    finally:
        temporary.unlink(missing_ok=True)
    checksum = archive.with_suffix(".zip.sha256")
    checksum.write_text(f"{digest(archive)}  {archive.name}\n", encoding="utf-8")
    print(f"Release archive: {archive}")
    print(f"SHA-256: {checksum}")
    return archive


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("publish", "validate", "fetch", "archive"))
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[1]
    if args.action == "publish":
        publish(project)
    elif args.action == "archive":
        archive_release(project)
    elif args.action == "fetch":
        for pin in load_lock(project)["artifacts"].values():
            artifact(project, pin)
    else:
        manifest = validate_release(project / "dist/third-party")
        print(f"Validated {len(manifest['components'])} Python components and all release materials")
